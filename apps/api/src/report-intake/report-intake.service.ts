import { createHash } from 'node:crypto';
import { Injectable } from '@nestjs/common';
import type { SubmitReportMetadata } from '@ftt/contracts';
import { PrismaService } from '../platform/index.js';
import type { Project } from '../projects/index.js';
import type { Report } from '../generated/prisma/client.js';

export interface SubmitReportInput {
  project: Project;
  commitSha: string;
  metadata: SubmitReportMetadata;
  body: Buffer;
}

/** Reports shown on a Project's Reports page (FR-30). */
const REPORTS_PAGE_SIZE = 100;

/**
 * Turns one HTTP submission into a stored `pending` Report (FR-05 … FR-11). Synchronous
 * checks only; parsing the body into Tests and Outcomes is the ReportProcessing module's job.
 *
 * Also the `report` table's read owner for ReadApi (design §4): no other module claims Report
 * reads until ReportQueue's lifecycle methods arrive in ticket 03.
 */
@Injectable()
export class ReportIntakeService {
  constructor(private readonly prisma: PrismaService) {}

  async submit({ project, commitSha, metadata, body }: SubmitReportInput): Promise<Report> {
    const contentHash = createHash('sha256').update(body).digest('hex');

    return this.prisma.$transaction(async (tx) => {
      const report = await tx.report.create({
        data: {
          projectId: project.id,
          commitSha,
          contentHash,
          sizeBytes: body.length,
          branch: metadata.branch,
          ciRunId: metadata.runId,
          ciRunAttempt: metadata.runAttempt,
          ciJob: metadata.job,
        },
      });
      // Prisma's generated Bytes type wants a plain ArrayBuffer-backed Uint8Array, not Buffer's
      // wider ArrayBufferLike.
      await tx.reportContent.create({ data: { reportId: report.id, body: new Uint8Array(body) } });
      return report;
    });
  }

  /** The Project's most recent Reports, newest first (FR-30). */
  listForProject(projectId: string): Promise<Report[]> {
    return this.prisma.report.findMany({
      where: { projectId },
      orderBy: { receivedAt: 'desc' },
      take: REPORTS_PAGE_SIZE,
    });
  }

  /** One Report, scoped to its Project so a Report from another Project is a miss (SRS §10). */
  findOne(projectId: string, reportId: string): Promise<Report | null> {
    return this.prisma.report.findFirst({ where: { id: reportId, projectId } });
  }
}
